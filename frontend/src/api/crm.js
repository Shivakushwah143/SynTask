import api from './axios'

export const crmApi = {
  getDashboard: () => api.get('/crm/dashboard'),
  getCompanies: (params) => api.get('/crm/companies', { params }),
  getCompany: (companyId) => api.get(`/crm/companies/${companyId}`),
  createCompany: (payload) => api.post('/crm/companies', payload),
  updateCompany: (companyId, payload) => api.patch(`/crm/companies/${companyId}`, payload),
  deleteCompany: (companyId) => api.delete(`/crm/companies/${companyId}`),
  getPipeline: (params) => api.get('/crm/pipeline', { params }),
  getLeads: (params) => api.get('/crm/leads', { params }),
  updatePipelineStage: (leadId, payload) => api.patch(`/crm/pipeline/${leadId}/stage`, payload),
  updateStageStatus: (leadId, stageStatus) => api.patch(`/crm/pipeline/${leadId}/status`, { stage_status: stageStatus }),
  updateLeadConversion: (leadId, payload) => api.patch(`/crm/pipeline/${leadId}/conversion`, payload),
  transferLeadToClients: (leadId) => api.post(`/crm/pipeline/${leadId}/transfer`),
  getPipelineHistory: (leadId) => api.get(`/crm/pipeline/history/${leadId}`),
  getDuplicateProspects: (params) => api.get('/crm/duplicates', { params }),
  getLeadTimeline: (leadId) => api.get(`/crm/leads/${leadId}/timeline`),
  getActivities: (params) => api.get('/crm/activities', { params }),
  createActivity: (payload) => api.post('/crm/activities', payload),
  updateActivity: (activityId, payload) => api.patch(`/crm/activities/${activityId}`, payload),
  deleteActivity: (activityId) => api.delete(`/crm/activities/${activityId}`),
  getLeadDeal: (leadId) => api.get(`/crm/leads/${leadId}/deal`),
  updateLeadDeal: (leadId, payload) => api.patch(`/crm/leads/${leadId}/deal`, payload),
  getLeadProposals: (leadId) => api.get(`/crm/leads/${leadId}/proposals`),
  createLeadProposal: (leadId, payload) => api.post(`/crm/leads/${leadId}/proposals`, payload),
  updateLeadProposal: (leadId, proposalId, payload) => api.patch(`/crm/leads/${leadId}/proposals/${proposalId}`, payload),
  archiveLeadProposal: (leadId, proposalId) => api.post(`/crm/leads/${leadId}/proposals/${proposalId}/archive`),
  getLeadFiles: (leadId) => api.get(`/crm/leads/${leadId}/files`),
  uploadLeadFile: (leadId, payload) => api.post(`/crm/leads/${leadId}/files`, payload),
  deleteLeadFile: (leadId, fileId) => api.delete(`/crm/leads/${leadId}/files/${fileId}`),
  getLeadNotes: (leadId) => api.get(`/crm/leads/${leadId}/notes`),
  createLeadNote: (leadId, payload) => api.post(`/crm/leads/${leadId}/notes`, payload),
  updateLeadNote: (leadId, noteId, payload) => api.patch(`/crm/leads/${leadId}/notes/${noteId}`, payload),
  deleteLeadNote: (leadId, noteId) => api.delete(`/crm/leads/${leadId}/notes/${noteId}`),
  getContacts: (params) => api.get('/crm/contacts', { params }),
  getContact: (contactId) => api.get(`/crm/contacts/${contactId}`),
  createContact: (payload) => api.post('/crm/contacts', payload),
  updateContact: (contactId, payload) => api.patch(`/crm/contacts/${contactId}`, payload),
  deleteContact: (contactId) => api.delete(`/crm/contacts/${contactId}`),
}
